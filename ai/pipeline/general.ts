function make(system: string, user: string, assistant: string, id: string): ChatExample {
  return {
    questionId: id,
    mode: 'general',
    messages: [
      { role: 'system', content: system },
      { role: 'user', content: user },
      { role: 'assistant', content: assistant },
    ],
  };
}

export function generalExamples(system: string): ChatExample[] {
  const out: ChatExample[] = [];
  VOCAB.forEach((v, i) => {
    const asks = [VOCAB_ASKS[i % VOCAB_ASKS.length], VOCAB_ASKS[(i + 1) % VOCAB_ASKS.length]] as string[];
    for (const a of asks)
      out.push(make(system, a.replace('WORD', v.en), `**${v.en}** = ${v.mn}. Жишээ: ${v.ex}`, `vocab-${i}`));
  });
  FIXED.forEach(([u, a], i) => {
    out.push(make(system, u, a, `general-${i}`));
  });
  return out;
}
